# caret RFE, resampling and parallel helpers, from the author's helper collection (functions not used here removed)

# metric and summary function --------------------------------------------------

# the summary function must return a named numeric vector holding the metric
validate_metric_config <- function(metric_value, summary_function) {
  test_data <- data.frame(obs = c(1, 2, 3, 4), pred = c(1.1, 1.9, 3.2, 3.8))
  metric_output <- summary_function(test_data)
  if (!is.numeric(metric_output)) {
    stop("The summary function must return a numeric named vector.")
  }
  if (is.null(names(metric_output))) {
    stop("The summary function must return named metrics.")
  }
  if (!metric_value %in% names(metric_output)) {
    stop("The selected metric '", metric_value, "' was not returned by the summary function. ",
         "Available metrics: ", paste(names(metric_output), collapse = ", "))
  }
  invisible(TRUE)
}

# caretFuncs for a regression RFE: the given summary, the metric passed to
# train() inside each subset, and a numeric prediction vector
make_rcaret_funcs <- function(metric_value, summary_function) {
  force(metric_value)
  force(summary_function)
  validate_metric_config(metric_value = metric_value, summary_function = summary_function)

  funcs <- caret::caretFuncs
  funcs$summary <- summary_function

  funcs$fit <- function(x, y, first, last, ...) {
    if (!is.numeric(y)) {
      stop("RFE received a non-numeric response inside fit. Class: ", paste(class(y), collapse = ", "))
    }
    dots <- list(...)
    # avoid duplicated or inherited metric arguments from caret internals
    dots$metric <- NULL
    args <- c(list(x = x, y = y, metric = metric_value), dots)
    do.call(what = caret::train, args = args)
  }

  funcs$pred <- function(object, x) {
    pred <- predict(object, x)
    if (is.matrix(pred)) {
      pred <- pred[, 1]
    }
    if (is.data.frame(pred)) {
      pred <- pred[[1]]
    }
    if (!is.numeric(pred)) {
      pred_numeric <- suppressWarnings(as.numeric(pred))
      if (any(is.na(pred_numeric) & !is.na(pred))) {
        stop("RFE prediction could not be safely converted to numeric. Class: ",
             paste(class(pred), collapse = ", "))
      }
      pred <- pred_numeric
    }
    pred
  }

  funcs
}

# resampling -------------------------------------------------------------------

# training indices of k folds by group (caret::groupKFold), repeated; each
# repeat seeded with seed + repeat - 1
make_repeated_group_folds <- function(group, k, repeats, seed) {
  if (length(group) == 0) {
    stop("The grouping vector is empty.")
  }
  n_groups <- dplyr::n_distinct(group)
  if (n_groups < 2) {
    stop("At least two groups are required to create group folds.")
  }
  k_use <- min(k, n_groups)

  fold_list <- purrr::map(seq_len(repeats), function(rep_id) {
    set.seed(seed + rep_id - 1)
    folds <- caret::groupKFold(group = group, k = k_use)
    names(folds) <- paste0("Repeat", rep_id, "_", names(folds))
    folds
  })

  unlist(fold_list, recursive = FALSE)
}

# drops degenerate resamples from a list of training indices: fewer than
# min_train_n training rows, fewer than min_holdout_n rows left for
# validation, or invalid indices. NULL (resampling generated by caret) is
# returned unchanged
validate_resampling_index <- function(index, n_rows, min_train_n = 2, min_holdout_n = 2) {
  if (is.null(index)) {
    return(NULL)
  }

  index_valid <- purrr::keep(index, function(idx) {
    idx <- unique(idx)
    length(idx) >= min_train_n &&
      all(!is.na(idx)) &&
      all(idx >= 1) &&
      all(idx <= n_rows) &&
      (n_rows - length(idx)) >= min_holdout_n
  })

  n_removed <- length(index) - length(index_valid)
  if (n_removed > 0) {
    warning(sprintf("validate_resampling_index: removed %d invalid/degenerate resampling fold(s) out of %d.",
                    n_removed, length(index)))
  }
  if (length(index_valid) == 0) {
    stop("validate_resampling_index: all resampling folds were invalid. Reduce the number of folds ",
         "or check the grouping variable.")
  }

  index_valid
}

# RFE subset sizes that exist for n_predictors candidates, plus the full set
make_valid_rfe_sizes <- function(rfe_size, n_predictors) {
  if (n_predictors < 1) {
    stop("No predictors are available for RFE.")
  }
  sizes <- rfe_size[rfe_size <= n_predictors]
  sizes <- sort(unique(c(sizes, n_predictors)))
  sizes <- sizes[sizes > 0]
  if (length(sizes) == 0) {
    stop("No valid RFE sizes were available after predictor filtering.")
  }
  sizes
}

# control objects --------------------------------------------------------------

make_train_control <- function(method, number, repeats = NULL, index = NULL,
                               summary_function, save_predictions = TRUE,
                               allow_parallel = FALSE) {
  if (identical(method, "repeatedcv")) {
    caret::trainControl(method = method, number = number, repeats = repeats, index = index,
                        savePredictions = save_predictions, summaryFunction = summary_function,
                        allowParallel = allow_parallel)
  } else {
    caret::trainControl(method = method, number = number, index = index,
                        savePredictions = save_predictions, summaryFunction = summary_function,
                        allowParallel = allow_parallel)
  }
}

make_rfe_control <- function(method, number, repeats = NULL, index = NULL,
                             functions_object, verbose = FALSE,
                             allow_parallel = FALSE) {
  if (identical(method, "repeatedcv")) {
    caret::rfeControl(method = method, number = number, repeats = repeats, index = index,
                      functions = functions_object, verbose = verbose, allowParallel = allow_parallel)
  } else {
    caret::rfeControl(method = method, number = number, index = index,
                      functions = functions_object, verbose = verbose, allowParallel = allow_parallel)
  }
}

# checks -----------------------------------------------------------------------

# the target exists, is numeric, has at least 3 finite and 2 distinct values
check_regression_target <- function(data, target_var, stage = "data_check") {
  if (!target_var %in% names(data)) {
    stop("Target variable was not found: ", target_var, " | stage: ", stage)
  }
  y <- data[[target_var]]
  if (!is.numeric(y)) {
    stop("Target variable is not numeric: ", target_var, " | class: ",
         paste(class(y), collapse = ", "), " | stage: ", stage)
  }
  if (sum(is.finite(y), na.rm = TRUE) < 3) {
    stop("Target variable has fewer than 3 finite values: ", target_var, " | stage: ", stage)
  }
  if (dplyr::n_distinct(y, na.rm = TRUE) < 2) {
    stop("Target variable has fewer than 2 unique values: ", target_var, " | stage: ", stage)
  }
  invisible(TRUE)
}

# parallel backend -------------------------------------------------------------

# PSOCK cluster registered for foreach, with the packages loaded and the
# objects of the global environment exported to every worker
setup_parallel_backend <- function(use_parallel, cores, packages, objects_to_export = character(0)) {
  if (!use_parallel) {
    foreach::registerDoSEQ()
    return(NULL)
  }

  cores_use <- max(1, min(cores, parallel::detectCores()))
  cl <- parallel::makeCluster(cores_use)

  parallel::clusterCall(cl, function(packages) {
    invisible(lapply(packages, require, character.only = TRUE))
    NULL
  }, packages)

  objects_to_export <- objects_to_export[vapply(objects_to_export, exists, logical(1), envir = .GlobalEnv)]
  if (length(objects_to_export) > 0) {
    parallel::clusterExport(cl, varlist = objects_to_export, envir = .GlobalEnv)
  }

  doParallel::registerDoParallel(cl)
  cl
}

close_parallel_backend <- function(cl) {
  if (!is.null(cl)) {
    parallel::stopCluster(cl)
  }
  foreach::registerDoSEQ()
  invisible(TRUE)
}
